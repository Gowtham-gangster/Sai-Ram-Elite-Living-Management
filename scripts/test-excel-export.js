require('dotenv').config();
const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

async function testExcelExport() {
  console.log('================================================================');
  console.log('   EXCEL WORKBOOK (.XLSX) EXPORT AUTOMATED VERIFICATION SUITE   ');
  console.log('================================================================\n');

  // 1. Authenticate to get session cookie
  const loginRes = await fetch('http://localhost:3000/api/auth/login', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'admin@sairam.com', password: 'admin123' }),
  });
  const cookieHeader = loginRes.headers.get('set-cookie');

  // 2. Fetch Reports Data
  console.log('--- 1. Fetching Live Reports Dataset ---');
  const repRes = await fetch('http://localhost:3000/api/reports', {
    headers: { cookie: cookieHeader || '' },
  });

  if (!repRes.ok) {
    throw new Error(`Failed to fetch /api/reports, status: ${repRes.status}`);
  }

  const data = await repRes.json();
  const { summary, reports } = data;
  console.log(`✅ Reports API returned summary: Total Rooms: ${summary.totalRooms}, Active Census: ${summary.totalActiveResidents}`);

  // 3. Test Excel Generation for Each Tab
  const testTabs = [
    {
      tabId: 'RESIDENTS',
      sheetName: 'Resident Census',
      filename: `SAIRAM_ELITE_LIVING_Resident_Census_2026-08-28.xlsx`,
      rows: reports.residentReport.map((r) => ({
        'Resident Name': r.fullName,
        'Room Number': String(r.roomNumber),
        'Floor': Number(r.floor),
        'Sharing Type': r.sharingType,
        'Phone Number': String(r.phone),
        'Alternate Phone': r.alternatePhone || 'N/A',
        'Email': r.email || 'N/A',
        'Agreed Monthly Rent (₹)': Number(r.agreedMonthlyRent),
        'Security Deposit (₹)': Number(r.securityDeposit),
        'Check-in Date': r.checkInDate ? new Date(r.checkInDate).toISOString().slice(0, 10) : 'N/A',
        'Expected Checkout Date': r.expectedCheckoutDate ? new Date(r.expectedCheckoutDate).toISOString().slice(0, 10) : 'N/A',
        'ID Proof Type': r.idProofType,
        'ID Proof Number (Masked)': r.idProofNumber,
        'Emergency Contact Name': r.emergencyContactName,
        'Emergency Contact Phone': String(r.emergencyContactPhone || 'N/A'),
        'Status': r.status,
      })),
    },
    {
      tabId: 'ROOMS',
      sheetName: 'Room Occupancy',
      filename: `SAIRAM_ELITE_LIVING_Room_Occupancy_2026-08-28.xlsx`,
      rows: reports.roomOccupancyReport.map((rm) => ({
        'Room Number': String(rm.roomNumber),
        'Floor': Number(rm.floor),
        'Sharing Type': rm.sharingType,
        'Total Capacity': Number(rm.capacity),
        'Active Residents': Number(rm.activeResidentsCount),
        'Available Spaces': Number(rm.availableSlots),
        'Occupancy Rate (%)': Number(rm.occupancyRatePercentage),
        'Base Monthly Rent (₹)': Number(rm.baseRent),
        'Current Realized Revenue (₹)': Number(rm.currentRealizedRevenue),
        'Potential Monthly Revenue (₹)': Number(rm.potentialMonthlyRevenue),
        'Status': rm.status,
        'Assigned Residents': rm.residents,
      })),
    },
    {
      tabId: 'PAYMENTS',
      sheetName: 'Payment Ledgers',
      filename: `SAIRAM_ELITE_LIVING_Payment_Ledgers_2026-08-28.xlsx`,
      rows: reports.monthlyPaymentReport.map((p) => ({
        'Resident Name': p.residentName,
        'Phone Number': String(p.phone),
        'Room Number': String(p.roomNumber),
        'Floor': Number(p.floor),
        'Billing Month': p.billingMonth,
        'Base Rent (₹)': Number(p.rentAmount),
        'Maintenance (₹)': Number(p.maintenanceAmount || 0),
        'Late Penalty (₹)': Number(p.penaltyAmount || 0),
        'Discount (₹)': Number(p.discountAmount || 0),
        'Total Due (₹)': Number(p.totalAmountDue),
        'Due Date': p.dueDate ? new Date(p.dueDate).toISOString().slice(0, 10) : 'N/A',
        'Paid Date': p.paidDate ? new Date(p.paidDate).toISOString().slice(0, 10) : 'N/A',
        'Status': p.status,
        'Payment Method': p.paymentMethod,
        'Receipt Number': p.receiptNumber,
        'Transaction Reference': p.transactionReference,
      })),
    },
    {
      tabId: 'COLLECTIONS',
      sheetName: 'Collections & Receipts',
      filename: `SAIRAM_ELITE_LIVING_Collections_Receipts_2026-08-28.xlsx`,
      rows: reports.collectionReport.map((rc) => ({
        'Receipt Number': rc.receiptNumber,
        'Resident Name': rc.residentName,
        'Room Number': String(rc.roomNumber),
        'Billing Month': rc.billingMonth,
        'Amount Paid (₹)': Number(rc.amountPaid),
        'Payment Date': rc.paymentDate ? new Date(rc.paymentDate).toISOString().slice(0, 10) : 'N/A',
        'Payment Method': rc.paymentMethod,
        'Generated By': rc.generatedBy,
        'Notes': rc.notes,
      })),
    },
    {
      tabId: 'CHECKOUTS',
      sheetName: 'Checkout History',
      filename: `SAIRAM_ELITE_LIVING_Checkout_History_2026-08-28.xlsx`,
      rows: reports.checkoutReport.map((c) => ({
        'Resident Name': c.fullName,
        'Phone Number': String(c.phone),
        'Room Number': String(c.roomNumber),
        'Floor': Number(c.floor),
        'Check-in Date': c.checkInDate ? new Date(c.checkInDate).toISOString().slice(0, 10) : 'N/A',
        'Checkout Date': c.checkOutDate ? new Date(c.checkOutDate).toISOString().slice(0, 10) : 'N/A',
        'Stay Duration (Days)': Number(c.stayDurationDays),
        'Security Deposit (₹)': Number(c.securityDeposit),
        'Status': c.status,
        'Notes': c.notes,
      })),
    },
  ];

  console.log('\n--- 2. Validating Excel Workbook Generation & Data Types ---');
  for (const tab of testTabs) {
    const rows = tab.rows.length > 0 ? tab.rows : [{ Status: 'No records found' }];
    const ws = XLSX.utils.json_to_sheet(rows);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, tab.sheetName);

    // Generate binary buffer
    const buf = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
    if (!buf || buf.length === 0) {
      throw new Error(`Failed to generate XLSX buffer for ${tab.tabId}`);
    }

    // Read back workbook
    const readWb = XLSX.read(buf, { type: 'buffer' });
    if (!readWb.SheetNames.includes(tab.sheetName)) {
      throw new Error(`Worksheet name "${tab.sheetName}" mismatch in generated workbook!`);
    }

    const parsedSheet = XLSX.utils.sheet_to_json(readWb.Sheets[tab.sheetName]);
    console.log(`✅ [${tab.tabId}] -> Filename: "${tab.filename}", Sheet: "${tab.sheetName}", Rows: ${parsedSheet.length}, Buffer Size: ${buf.length} bytes`);
  }

  // 4. Privacy & Masking Check
  console.log('\n--- 3. Verifying Privacy & Aadhaar Masking in Export ---');
  for (const r of reports.residentReport) {
    if (r.idProofNumber && r.idProofNumber !== 'N/A') {
      const cleanDigits = String(r.idProofNumber).replace(/\D/g, '');
      if (cleanDigits.length === 12) {
        throw new Error(`Unmasked 12-digit Aadhaar detected in export: ${r.idProofNumber}`);
      }
    }
  }
  console.log('✅ Privacy Verified: Full Aadhaar numbers are masked (e.g. XXXX-XXXX-3258).');

  // 5. Verify CSV export has been completely replaced
  console.log('\n--- 4. Verifying CSV Export Elimination ---');
  const repFileContent = fs.readFileSync(
    path.join(__dirname, '../src/app/(protected)/reports/page.tsx'),
    'utf8'
  );
  if (repFileContent.includes('exportCsv') || repFileContent.includes('Export CSV')) {
    throw new Error('Found lingering CSV export references in Reports page!');
  }
  console.log('✅ CSV Export fully replaced by "Export Excel" (.xlsx).');

  console.log('\n================================================================');
  console.log('   🎉 EXCEL EXPORT AUTOMATED TESTS PASSED 100% (ALL CHECKS)     ');
  console.log('================================================================\n');
}

testExcelExport().catch((err) => {
  console.error('❌ Test failed:', err);
  process.exit(1);
});
